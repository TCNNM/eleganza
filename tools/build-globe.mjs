#!/usr/bin/env node
// Build a compact land bitmask for the dotted globe from Natural Earth 110m land.
// Source: world-atlas land-110m.json (TopoJSON, public domain Natural Earth data).
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const STEP = 1.5; // degrees per cell
const W = Math.round(360 / STEP);
const H = Math.round(180 / STEP);

const topo = JSON.parse(await readFile(path.join(root, 'assets/land-110m.json'), 'utf8'));

function decodeArcs(topology) {
  const [sx, sy] = topology.transform.scale;
  const [tx, ty] = topology.transform.translate;
  return topology.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * sx + tx, y * sy + ty];
    });
  });
}

function ringPoints(arcs, indices) {
  const pts = [];
  for (const i of indices) {
    const idx = i < 0 ? ~i : i;
    const arc = arcs[idx];
    const seq = i < 0 ? [...arc].reverse() : arc;
    for (let k = pts.length ? 1 : 0; k < seq.length; k += 1) pts.push(seq[k]);
  }
  return pts;
}

function collectRings(geometry, arcs, out) {
  if (!geometry) return;
  if (geometry.type === 'GeometryCollection') {
    for (const g of geometry.geometries || []) collectRings(g, arcs, out);
    return;
  }
  if (geometry.type === 'Polygon') {
    for (const ring of geometry.arcs) out.push(ringPoints(arcs, ring));
    return;
  }
  if (geometry.type === 'MultiPolygon') {
    for (const poly of geometry.arcs) {
      for (const ring of poly) out.push(ringPoints(arcs, ring));
    }
  }
}

const arcs = decodeArcs(topo);
const rings = [];
for (const g of topo.objects.land.geometries) collectRings(g, arcs, rings);

// Scanline rasterisation, even-odd across every ring.
const bits = new Uint8Array(W * H);
for (let row = 0; row < H; row += 1) {
  const lat = -90 + (row + 0.5) * STEP;
  const xs = [];
  for (const ring of rings) {
    for (let i = 0; i < ring.length; i += 1) {
      const [x1, y1] = ring[i];
      const [x2, y2] = ring[(i + 1) % ring.length];
      if ((y1 > lat) === (y2 > lat)) continue;
      const x = x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1);
      xs.push(x);
    }
  }
  xs.sort((a, b) => a - b);
  for (let i = 0; i + 1 < xs.length; i += 2) {
    const from = Math.max(0, Math.ceil((xs[i] + 180) / STEP - 0.5));
    const to = Math.min(W - 1, Math.floor((xs[i + 1] + 180) / STEP - 0.5));
    for (let col = from; col <= to; col += 1) bits[row * W + col] = 1;
  }
}

// Pack MSB-first and base64 encode.
const bytes = Buffer.alloc(Math.ceil(bits.length / 8));
for (let i = 0; i < bits.length; i += 1) {
  if (bits[i]) bytes[i >> 3] |= 0x80 >> (i & 7);
}
const data = bytes.toString('base64');
const landCount = bits.reduce((a, b) => a + b, 0);
const output = `// Generated by tools/build-globe.mjs — Natural Earth 110m land, ${STEP}° grid.
// Do not edit by hand.
window.ELEGANZA_LAND = {
  step: ${STEP},
  width: ${W},
  height: ${H},
  data: ${JSON.stringify(data)},
};
`;

await writeFile(path.join(root, 'public/globe-land.js'), output);
console.log(`globe-land.js: ${W}x${H}, ${landCount} land cells, ${output.length} bytes`);
